export function diceInsight(planet:number,sign:number,house:number) {
 if([planet,sign,house].some(n=>!Number.isInteger(n)||n<0||n>11)) throw new Error('无效的星骰选项');
 const motive=motives[planet],style=styles[sign],context=contexts[house];
 const slowPlanet=[1,6,11].includes(planet),fastPlanet=[4,5,7,10].includes(planet);
 const interplay=slowPlanet&&style[2]==='fast'
  ? '这里有一种节奏上的拉扯：一方面希望获得稳定和可依赖的依据，另一方面又想尽快推进。把行动分成试行与正式承诺两步，可以兼顾两种需要。'
  :fastPlanet&&style[2]==='steady'
  ? '扩展或改变的动力遇到较谨慎的表达方式，可能表现为想动却不断检查条件。可以事先定义“准备到什么程度就开始”，用小试验代替无限准备。'
  :[4,6,9].includes(planet)&&style[2]==='feeling'
  ? '行动、责任或控制的需要，可能通过敏感的感受间接表达。若习惯先忍耐再突然回应，可以提前说清请求，让别人有机会理解并协商。'
  :[3,8].includes(planet)&&style[2]==='open'
  ? '建立共鸣的愿望与多角度思考可以互相支持，但也可能让每种答案都显得合理。协商之后，需要落到一个明确约定上。'
  :`两者可以互相支持：把「${motive[0]}」转化为具体表达，并通过「${style[1]}」检查方式是否合适。动力本身并不决定结果，仍要看现实中的条件与反馈。`;
 return {
  title:`${planets[planet][1]} × ${signs[sign][1]} × 第${house+1}宫`,
  paragraphs:[
   `结合《行星》《星座》《十二宮位》的对应主题，这组骰子的主线可以理解为：在「${houses[house]}」领域，尝试${motive[0]}，并以${style[0]}的方式表达。`,
   `放到具体生活中，可以对照${context[0]}。例如，当这类事情让你反复在意时，值得分辨：你想处理的是眼前安排，还是安排背后尚未被回应的需要。${interplay}`,
   `需要留意的失衡是：${motive[1]}。${signs[sign][1]}的表达方式也提醒你${style[1]}。这些是供你与真实经历核对的可能性，不代表他人的动机或未来已经确定。`,
  ],
  steps:[
   {title:'先辨认真正的需要',text:`${motive[2]}。用最近一件涉及第${house+1}宫的具体经历来核对，区分发生的事实与自己的解释。`},
   {title:'落实到当前领域',text:`${context[1]}。进行时，试着${style[1]}；一次只调整一个重点，方便判断效果。`},
   {title:'观察结果，再作调整',text:`完成后安排一次回看，观察${context[2]}。如果没有改善，先检查信息、共识和方法是否足够，再决定继续、调整或暂停。`},
  ],
 };
}
